create table if not exists public.items (
  id bigint generated by default as identity primary key,
  title text not null,
  type text not null check (type in ('lost', 'found')),
  description text not null,
  category text not null,
  location text not null,
  image_url text,
  user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.items
  add column if not exists user_id uuid references auth.users(id) on delete set null,
  add column if not exists brand text not null default '',
  add column if not exists color text not null default '',
  add column if not exists city text not null default '',
  add column if not exists area text not null default '',
  add column if not exists date_lost date,
  add column if not exists approx_time text not null default '',
  add column if not exists latitude double precision,
  add column if not exists longitude double precision,
  add column if not exists image_urls text[] not null default '{}';

create table if not exists public.item_verification_questions (
  item_id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  questions jsonb not null,
  created_at timestamptz not null default now()
);

alter table public.item_verification_questions enable row level security;

drop policy if exists item_verification_questions_owner_read
  on public.item_verification_questions;
create policy item_verification_questions_owner_read
  on public.item_verification_questions
  for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists item_verification_questions_owner_delete
  on public.item_verification_questions;
create policy item_verification_questions_owner_delete
  on public.item_verification_questions
  for delete to authenticated
  using ((select auth.uid()) = user_id);

grant select, delete on public.item_verification_questions to authenticated;

alter table public.items enable row level security;

drop policy if exists items_public_read on public.items;
create policy items_public_read
  on public.items
  for select to anon, authenticated
  using (true);

revoke select on public.items from anon, authenticated;
grant select (id, title, type, description, category, location, image_url, created_at)
  on public.items to anon, authenticated;

create or replace function public.create_lost_found_report(
  p_item jsonb,
  p_verification_questions jsonb
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_item_id text;
begin
  if v_user_id is null then
    raise exception 'Please log in before reporting an item.';
  end if;

  if jsonb_typeof(p_verification_questions) <> 'array' then
    raise exception 'Verification questions must be an array.';
  end if;

  insert into public.items (
    title,
    type,
    description,
    category,
    location,
    image_url,
    user_id,
    brand,
    color,
    city,
    area,
    date_lost,
    approx_time,
    latitude,
    longitude,
    image_urls
  )
  values (
    p_item ->> 'title',
    'lost',
    p_item ->> 'description',
    p_item ->> 'category',
    p_item ->> 'location',
    nullif(p_item -> 'image_urls' ->> 0, ''),
    v_user_id,
    coalesce(p_item ->> 'brand', ''),
    coalesce(p_item ->> 'color', ''),
    coalesce(p_item ->> 'city', ''),
    coalesce(p_item ->> 'area', ''),
    nullif(p_item ->> 'date_lost', '')::date,
    coalesce(p_item ->> 'approx_time', ''),
    nullif(p_item ->> 'latitude', '')::double precision,
    nullif(p_item ->> 'longitude', '')::double precision,
    array(
      select jsonb_array_elements_text(
        coalesce(p_item -> 'image_urls', '[]'::jsonb)
      )
    )
  )
  returning id::text into v_item_id;

  insert into public.item_verification_questions (item_id, user_id, questions)
  values (v_item_id, v_user_id, p_verification_questions);

  return v_item_id;
end;
$$;

revoke all on function public.create_lost_found_report(jsonb, jsonb) from public, anon;
grant execute on function public.create_lost_found_report(jsonb, jsonb) to authenticated;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'item-images',
  'item-images',
  true,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp', 'image/gif']
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists item_images_owner_upload on storage.objects;
create policy item_images_owner_upload
  on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'item-images'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists item_images_owner_delete on storage.objects;
create policy item_images_owner_delete
  on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'item-images'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );
